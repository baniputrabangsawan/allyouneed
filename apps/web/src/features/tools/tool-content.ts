export function getToolPageCopy(slug: string, locale: Locale): ToolPageCopy | undefined {
  const entry = toolPageContent[slug]
  if (!entry) return undefined
  return entry[locale] ?? entry.en
}

const GENERIC_PHRASES = [
  'Open the tool page.',
  'Add your file or text.',
  'Choose the available options.',
  'Process the tool.',
  'Works in a focused web interface.',
  'Uses clear processing labels.',
  'Formats depend on the input used with this tool.',
  'quickly with a focused, easy-to-use tool.',
  'online with clear controls and privacy-conscious processing.',
]

export function copyLooksGeneric(copy: ToolPageCopy): string | undefined {
  const haystack = [copy.shortDescription, copy.description, copy.intro, ...copy.howTo, ...copy.benefits].join('\n')
  return GENERIC_PHRASES.find((phrase) => haystack.includes(phrase))
}
